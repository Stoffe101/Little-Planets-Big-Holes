def dig_soft(seed):
    r = np.random.default_rng(seed)
    d = 0.24
    n = bandpass(r.uniform(-1, 1, int(d * SR)), 150, 1500 + 300 * r.random()) * env(d, 0.003, 0.11, 5)
    thump = sweep(110 + 20 * r.random(), 48, d, 0.6) * env(d, 0.002, 0.09, 5) * 0.9
    grains = np.zeros(int(d * SR))
    for _ in range(9):
        g = bandpass(r.uniform(-1, 1, int(0.02 * SR)), 900, 4000) * env(0.02, 0.001, 0.008)
        place(grains, g, 0.03 + r.random() * 0.15, 0.35 * r.random())
    return n * 0.9 + thump + grains

