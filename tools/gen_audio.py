    ring = sum(tone(f * (1 + 0.04 * r.random()), d) * a for f, a in ((640, .5), (1010, .35), (1730, .25))) * env(d, 0.001, 0.06, 6) * 0.45
    rubble = bandpass(r.uniform(-1, 1, int(d * SR)), 300, 2200) * env(d, 0.03, 0.2, 4) * 0.35
    return crack * 0.8 + thump + ring + rubble

