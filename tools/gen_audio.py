def swish(seed):
    r = np.random.default_rng(seed)
    d = 0.2
    n = r.uniform(-1, 1, int(d * SR))
    out = np.zeros_like(n)
    # crude moving band: mix a few bands with staggered envelopes
    for i, (lo, hi) in enumerate(((400, 900), (800, 1700), (1500, 3200), (2600, 5200))):
        e = np.exp(-((t(d) - 0.03 - 0.035 * i) / 0.035) ** 2)
        out += bandpass(n, lo, hi) * e
    return out

