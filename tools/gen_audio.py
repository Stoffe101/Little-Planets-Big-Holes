#!/usr/bin/env python3
"""Synthesises every sound effect and music loop for Little Planets, Big Holes.

All audio in the game is original and generated by this script (numpy only), so the
repository contains no third-party audio. Run:  python3 tools/gen_audio.py
Music is rendered to WAV and converted to OGG Vorbis with ffmpeg when available.
"""
import os, subprocess, sys, wave
import numpy as np

SR = 44100
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets", "audio")
rng = np.random.default_rng(1234)


def t(dur, sr=SR):
    return np.arange(int(dur * sr)) / sr

def env(dur, attack=0.004, decay=None, curve=4.0, sr=SR):
    n = int(dur * sr)
    x = np.arange(n) / sr
    a = np.clip(x / max(attack, 1e-5), 0, 1)
    d = np.exp(-curve * x / (decay or dur))
    out = a * d
    fade = min(n, int(0.008 * sr))
    out[-fade:] *= np.linspace(1, 0, fade)
    return out

def noise(dur, sr=SR):
    return rng.uniform(-1, 1, int(dur * sr))

def bandpass(x, lo, hi, sr=SR, soft=0.25):
    """FFT band-pass with raised-cosine skirts (no scipy needed)."""
    X = np.fft.rfft(x)
    f = np.fft.rfftfreq(len(x), 1 / sr)
    m = np.ones_like(f)
    if lo > 0:
        w = lo * soft
        m *= np.clip((f - (lo - w)) / (2 * w + 1e-9), 0, 1)
    if hi < sr / 2:
        w = hi * soft
        m *= np.clip(((hi + w) - f) / (2 * w + 1e-9), 0, 1)
    m = 0.5 - 0.5 * np.cos(np.pi * m)
    return np.fft.irfft(X * m, len(x))

def sweep(f0, f1, dur, shape=1.0, sr=SR):
    x = t(dur, sr)
    k = (x / dur) ** shape
    f = f0 + (f1 - f0) * k
    return np.sin(2 * np.pi * np.cumsum(f) / sr)

def tone(f, dur, sr=SR, phase=0.0):
    return np.sin(2 * np.pi * f * t(dur, sr) + phase)

def bell(f, dur, partials=((1, 1.0), (2.76, 0.45), (5.4, 0.25), (8.9, 0.12)), decay=None, sr=SR):
    out = np.zeros(int(dur * sr))
    for mult, amp in partials:
        d = (decay or dur) / (1 + 0.6 * (mult - 1))
        out += amp * tone(f * mult, dur, sr) * env(dur, 0.002, d, 5.0, sr)
    return out

def place(buf, snd, at, gain=1.0, sr=SR):
    i = int(at * sr)
    n = min(len(snd), len(buf) - i)
    if n > 0:
        buf[i:i + n] += snd[:n] * gain
    return buf

def norm(x, peak=0.89):
    m = np.max(np.abs(x)) + 1e-9
    return x / m * peak

def soft_clip(x, drive=1.5):
    return np.tanh(x * drive) / np.tanh(drive)

def loopify(x, xfade=0.08, sr=SR):
    """Cross-fades the tail into the head so the buffer loops seamlessly."""
    n = int(xfade * sr)
    head, tail = x[:n].copy(), x[-n:].copy()
    w = np.linspace(0, 1, n)
    out = x[:-n].copy()
    out[:n] = head * w + tail * (1 - w)
    return out

def save(name, x, peak=0.89, sr=SR):
    x = norm(np.asarray(x, dtype=np.float64), peak)
    path = os.path.join(OUT, name + ".wav")
    with wave.open(path, "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(sr)
        w.writeframes((np.clip(x, -1, 1) * 32767).astype("<i2").tobytes())
    return path


