def save_music(name, x, sr=32000):
    path = save(name, x, 0.7, sr)
    ogg = path[:-4] + ".ogg"
    try:
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", path, "-c:a", "libvorbis", "-q:a", "4", ogg], check=True)
        os.remove(path)
        return ogg
    except Exception as e:   # keep the WAV if ffmpeg is unavailable
        print("ffmpeg unavailable, keeping WAV:", e)
        return path


