# ---------------------------------------------------------------- music

def pluck(f, dur, sr):
    x = np.arange(int(dur * sr)) / sr
    return (np.sin(2 * np.pi * f * x) + 0.4 * np.sin(2 * np.pi * 2 * f * x) + 0.15 * np.sin(2 * np.pi * 3 * f * x)) * np.exp(-3.2 * x) * np.clip(x / 0.004, 0, 1)

def pad(f, dur, sr):
    x = np.arange(int(dur * sr)) / sr
    e = np.sin(np.pi * np.clip(x / dur, 0, 1)) ** 0.8
    v = np.sin(2 * np.pi * f * x + 0.4 * np.sin(2 * np.pi * 0.2 * x)) + 0.5 * np.sin(2 * np.pi * f * 1.004 * x) + 0.3 * np.sin(2 * np.pi * f * 2.0 * x) + 0.1 * np.sin(2 * np.pi * f * 3.0 * x)
    return v * e

NOTE = {n: 440.0 * 2 ** ((i - 9) / 12) for i, n in enumerate(["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"])}
def hz(name, octave):
    return NOTE[name] * 2 ** (octave - 4)

def music(chords, scale, seed, bar=4.0, sr=32000, bell_like=False):
    r = np.random.default_rng(seed)
    total = bar * len(chords)
    tail = 3.0
    buf = np.zeros(int((total + tail) * sr))
    for i, chord in enumerate(chords):
        at = i * bar
        for j, (n, o) in enumerate(chord):
            place(buf, pad(hz(n, o), bar * 1.35, sr), at, 0.11 if j else 0.16, sr)
        # soft bass pulse
        n0, o0 = chord[0]
        for b in (0.0, 2.0):
            place(buf, pluck(hz(n0, o0 - 1), 1.8, sr), at + b, 0.22, sr)
        # sparse melody from the scale, leaning on chord tones
        steps = 8
        for s in range(steps):
            if r.random() < (0.5 if s % 2 == 0 else 0.22):
                n, o = scale[r.integers(0, len(scale))]
                dur = 1.6
                v = pluck(hz(n, o), dur, sr)
                if bell_like:
                    shimmer = pluck(hz(n, o) * 2.76, dur * 0.6, sr)
                    v = v + 0.3 * np.pad(shimmer, (0, len(v) - len(shimmer)))
                place(buf, v, at + s * bar / steps + r.uniform(-0.015, 0.015), 0.12 + 0.07 * r.random(), sr)
                if r.random() < 0.3:   # echo
                    place(buf, v, at + s * bar / steps + 0.375, 0.05, sr)
    # fold the reverb-ish tail back onto the start so the loop is seamless
    n_total = int(total * sr)
    out = buf[:n_total].copy()
    out[: len(buf) - n_total] += buf[n_total:]
    return out

